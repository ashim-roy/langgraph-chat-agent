from langgraph.graph import StateGraph, START
from dotenv import load_dotenv
from langchain_openai import ChatOpenAI
from langchain_community.tools import DuckDuckGoSearchRun
from typing import TypedDict, Annotated
from langchain_core.messages import BaseMessage, HumanMessage
from langgraph.graph.message import add_messages
from langgraph.prebuilt import ToolNode, tools_condition
from langchain_core.tools import tool

# Load environment variables (such as your OpenAI API key) from a local .env file
load_dotenv()  

# Initialize the synchronous ChatOpenAI model
llm = ChatOpenAI(model="gpt-5")

# Define a custom tool using the @tool decorator to perform basic arithmetic
@tool
def calculator(first_num: float, second_num: float, operation: str) -> dict:
    """
    Perform a basic arithmetic operation on two numbers.
    Supported operations: add, sub, mul, div
    """
    try:
        if operation == "add":
            result = first_num + second_num
        elif operation == "sub":
            result = first_num - second_num
        elif operation == "mul":
            result = first_num * second_num
        elif operation == "div":
            if second_num == 0:
                return {"error": "Division by zero is not allowed"}
            result = first_num / second_num
        else:
            return {"error": f"Unsupported operation '{operation}'"}
        
        return {"first_num": first_num, "second_num": second_num, "operation": operation, "result": result}
    except Exception as e:
        return {"error": str(e)}

# Register the tools list and bind them to the LLM
tools = [calculator]
llm_with_tools = llm.bind_tools(tools)

# Define the state structure for the graph, using add_messages to append new chat history
class ChatState(TypedDict):
    messages: Annotated[list[BaseMessage], add_messages]

# Node: Handles the conversation and invokes the LLM with tool binding
def chat_node(state: ChatState):
    messages = state["messages"]
    response = llm_with_tools.invoke(messages)
    return {'messages': [response]}

# Prebuilt ToolNode to execute any tool calls requested by the LLM
tool_node = ToolNode(tools)

# Initialize the StateGraph with the defined ChatState schema
graph = StateGraph(ChatState)

# Add the chat and tool execution nodes to the graph
graph.add_node("chat_node", chat_node)
graph.add_node("tools", tool_node)

# Define the routing and connections between graph nodes
# 1. Start execution flow at the chat_node
graph.add_edge(START, "chat_node")

# 2. Use tools_condition to check if the LLM wants to call a tool; routes to "tools" if yes, ends if no
graph.add_conditional_edges("chat_node", tools_condition)

# 3. After the tool runs, loop back to the chat_node so the LLM can process the result
graph.add_edge("tools", "chat_node")

# Compile the graph into an executable synchronous workflow
chatbot = graph.compile()

# Invoke the compiled graph synchronously with a prompt specifying a task and a persona
result = chatbot.invoke({
    "messages": [
        HumanMessage(content="Find the modulus of 132354 and 23 and give answer like a cricket commentator.")
    ]
})

# Print out the content of the final message generated by the model
print(result['messages'][-1].content)