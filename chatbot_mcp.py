from langgraph.graph import StateGraph, START
from dotenv import load_dotenv
from langchain_openai import ChatOpenAI
from langchain_community.tools import DuckDuckGoSearchRun
from typing import TypedDict, Annotated
from langchain_core.messages import BaseMessage, HumanMessage
from langgraph.graph.message import add_messages
from langgraph.prebuilt import ToolNode, tools_condition
from langchain_core.tools import tool
import asyncio
from langchain_mcp_adapters.client import MultiServerMCPClient

# Load environment variables (like API keys) from a local .env file
load_dotenv()  

# Initialize the ChatOpenAI model
llm = ChatOpenAI(model="gpt-5")

# Initialize the MultiServerMCPClient to fetch tools dynamically from external MCP servers
client = MultiServerMCPClient(
    {
        "arith": {
            "transport": "stdio",
            "command": "python3",          
            "args": ["/Users/nitish/Desktop/mcp-math-server/main.py"],
        },
        "expense": {
            "transport": "streamable_http",  # Use "sse" if streamable_http fails
            "url": "https://splendid-gold-dingo.fastmcp.app/mcp"
        }
    }
)

# Define the state structure for the graph, using add_messages to append new messages to history
class ChatState(TypedDict):
    messages: Annotated[list[BaseMessage], add_messages]


async def build_graph():
    """Asynchronously builds, configures, and compiles the LangGraph workflow."""

    # Dynamically fetch tools from the configured MCP servers
    tools = await client.get_tools()

    # Print available tools for debugging/inspection
    print(tools)

    # Bind the fetched tools to the LLM
    llm_with_tools = llm.bind_tools(tools)

    # Node: Handles conversation and decides whether to call a tool or reply directly
    async def chat_node(state: ChatState):
        messages = state["messages"]
        response = await llm_with_tools.ainvoke(messages)
        return {'messages': [response]}

    # Prebuilt ToolNode to execute any tools requested by the LLM
    tool_node = ToolNode(tools)

    # Initialize the StateGraph with our ChatState schema
    graph = StateGraph(ChatState)

    # Add nodes to the graph
    graph.add_node("chat_node", chat_node)
    graph.add_node("tools", tool_node)

    # Define graph routing and connections
    # 1. Start execution at the chat_node
    graph.add_edge(START, "chat_node")
    
    # 2. Use tools_condition to check if a tool needs to be called; route to "tools" if yes, else end
    graph.add_conditional_edges("chat_node", tools_condition)
    
    # 3. Feed tool execution results back into the chat_node for final synthesis
    graph.add_edge("tools", "chat_node")

    # Compile the graph into an executable application
    chatbot = graph.compile()

    return chatbot


async def main():
    # Asynchronously build the compiled graph (since tool fetching requires an async call)
    chatbot = await build_graph()

    # Invoke the graph asynchronously with a query requesting expense information
    result = await chatbot.ainvoke({
        "messages": [
            HumanMessage(content="Give me all my expenses for the month of Nov from 1 Nov to 30 Nov")
        ]
    })

    # Print the final response content generated by the LLM
    print(result['messages'][-1].content)


if __name__ == '__main__':
    # Run the asynchronous main entry point
    asyncio.run(main())